export function isLocale(v: unknown): v is Locale {
  return v === "en" || v === "es" || v === "pt-BR";
}
export function browserLocale(v: string): Locale {
  return v.toLowerCase().startsWith("pt")
    ? "pt-BR"
    : v.toLowerCase().startsWith("es")
      ? "es"
      : "en";
}
